local function install()
	if not mr then return nil, "memreader Plus is not loaded" end
	if bm:is_multiplayer() then
		-- caves from an earlier single player battle stay in the game: an empty list sends every one to CA's code
		local info = mr.hook_info and mr.hook_info(at(SITES.climb))
		if info and info.kind == "cave" then mr.write(mr.read_pointer(info.cave, BLOCK_AT), B.count, mr.uint32(0)) end
		return nil, "multiplayer battle: single player only, walls stay vanilla"
	end
	if not (mr.patcher and mr.game_alloc and mr.hook_info and mr.read_original and mr.alloc and mr.call) then
		return nil, "memreader Plus is missing native bridge functions: update it"
	end
	local base = mr.base
	-- game Lua numbers are float32, so every RVA travels as {high 16 bits, low 16 bits}
	local pe = mr.read_int32(base, 0x3c)
	local build = string.format("%04x%04x", mr.read_uint16(base, pe + 10), mr.read_uint16(base, pe + 8))
	if build ~= BUILD then return nil, "game build " .. build .. " is not " .. BUILD .. ": walls stay vanilla until the mod is updated" end
	for _, name in ipairs(CAVE_ORDER) do
		local site_bytes = string.char(unpack(SITE_BYTES[name]))
		if mr.read_original(at(SITES[name]), 0, #site_bytes) ~= site_bytes then return nil, "the " .. name .. " check is not the code the cave expects" end
	end
	-- a cave stays for the game session; a later battle finds its block in the first one's mov rax, <block>
	local info = mr.hook_info(at(SITES.climb))
	local block = info and info.kind == "cave" and mr.read_pointer(info.cave, BLOCK_AT) or mr.game_alloc(B.size)
	mr.write(block, B.count, mr.uint32(0))
	for field, hl in pairs(CALLS) do mr.write(block, B[field], at(hl)) end
	mr.write(block, B.wall_radius, WALL_RADIUS)
	local hex = mr.tostring(block)
	local patcher = mr.patcher("derpy_artillery_walls")
	for _, name in ipairs(CAVE_ORDER) do
		local bytes = {unpack(CAVES[name])}
		for i = 0, 7 do bytes[CAVE_BLOCK_AT[name] + i + 1] = tonumber(hex:sub(15 - 2 * i, 16 - 2 * i), 16) end -- low byte first
		local cave, why = patcher:cave(name, at(SITES[name]), string.char(unpack(bytes)))
		if not cave then return nil, "the " .. name .. " cave: " .. tostring(why) end
	end
	return block
end

