-- Physical artillery and crew can jam at stairs. Recovery requires a quiet motion window.
local STALL = 5000 -- ms without movement or an engine turning
-- A ground recovery waits longer: on a legitimate stair climb the engines stood still for 28 s while their crew went
-- up ahead of them (2026-11-01), and a wall exit queues the same way.
local GROUND_STALL = 20000
-- and tolerates a shuffle: engines held at a wall edge wander two metres back and forth for ever (2026-11-01)
local GROUND_DRIFT = 4
-- Crew trickling down one at a time count as progress, and four engines wedged on a walkway sat 70 s behind a
-- trickle that never ended (2026-11-01). Engines that have not moved this long are stuck whatever the crew do.
local GROUND_STALL_ENGINES = 40000
local STALL_REACH = 80 -- m: only nearby orders are retried
local COOL = 2000 -- ms before judging a retried order
local WALL_TOP = 2 -- m above the terrain: an ordered point this high is on a wall, not a ground exit
-- A stair is a surface too: one helstorm engine stood on the stair 3.2 m under its three on the roof for 500 s and
-- the order read as done (2026-11-02 10:45). For a wall order an engine is up within this of the order's height.
local WALL_LEVEL = 2
local NUDGE = 30000
-- An attack order is not a move. CA's `unit:ordered_position()` returns the unit's CURRENT position while it is
-- attacking (battle_unit.html), and the order struct still reads as a MOVE, so a wall battery given a target read as
-- a ground-height order with every engine on the wrong side of it: nudged at 35 s, dropped to the ground at 65 s,
-- for both Altdorf batteries (2026-11-01 21:00, script_log_011126_2052). An order whose point is where the unit
-- already stands has nothing to recover.
local ATTACK_HOLD = 1 -- m between the ordered point and the unit's own position that reads as an attack
-- A lagging crewman near his wall slot may have the slot moved under him.
local CREW_SNAP = 2000
local CREW_CLOSING = 0.25
local CREW_REACH = 8
local CREW_RISE = 3
local SLOT_MAX = 128 -- a slot count above this is not a slot table: vanilla tops out at 48 crew on one engine (the
-- Warp-Doom Magma Cannon, the Queen Bess); at 32 both ran with no crew handling at all (2026-11-09). checked by
-- gen_artillery_walls.py --check against land_units/main_units
-- Crew spots off the wall. An engine lays its crew out on spots around it, the pushers in a file a metre apart behind
-- it (exe+308dde4), and the game places each spot on the engine's own surface (exe+3086a80). At a stair top, a roof
-- edge or a narrow walkway a spot behind the gun lands on the ground below: its man walks off the wall to it or paces
-- at the edge, and the engine waits for him (2026-11-01: the four pusher spots of a gatehouse engine placed on the
-- ground 20 m down, their men idle there). On a wall such a spot is pulled in toward its gun, then turned to the gun's
-- side, until the game places it on the wall; CA's spot goes back when the engine leaves the wall. A man the crew rule
-- finds stuck short of his spot on the wall, at his gun's level, gets the spot moved to him instead of being lifted.
local SPOT_TRIES = {{0.6, 0}, {0.35, 0}, {0.4, 1}, {0.4, -1}} -- a scale toward the gun, then a quarter turn to a side
local SPOT_LAST = 2 -- the try kept when none lands on the wall: the nearest behind the gun
local SPOT_DROP = 3 -- m above or below its gun: a spot placed this far off the gun's level is off the wall
local SPOT_REACH = 7 -- m: a spot moves to its man only this near the gun, about CA's own furthest spot
local SPOT_SETTLE = 400 -- ms for the game to place a written spot before it is judged
local SPOT_GUN = {base = 0xd78, turn = 0xd98} -- the engine body's location and u16 heading its spots are laid from

local function bearing_to(x0, z0, x1, z1) return math.deg(math.atan2(x1 - x0, z1 - z0)) % 360 end

-- Engine records are {key=, x=, z=, path=, crew={{key=, x=, y=, z=, sx=, sy=, sz=, resolved=, manned=}, ...}} with
-- the slot's point at sx/sy/sz and path the engine's own path state. Returns crew whose slots may be adjusted.
local function crew_step(state, now, engines)
	state.crew = state.crew or {}
	local seen, place = {}, {}
	for _, e in ipairs(engines) do
		local prev = state.crew[e.key]
		local still = prev and (e.x - prev.x)^2 + (e.z - prev.z)^2 <= CREW_CLOSING^2
		local rec = still and prev or {x = e.x, z = e.z, men = {}, placed = {}}
		state.crew[e.key], seen[e.key] = rec, true
		for _, m in ipairs(e.crew) do
			local d = math.sqrt((m.x - m.sx)^2 + (m.z - m.sz)^2)
			local far = d > CREW_REACH or math.abs(m.y - m.sy) > CREW_RISE
			-- a standing engine (path 0) counts too while its man still walks: a pusher spot laid inside the parapet kept two
		-- docked helstorms out of their deploy (+0xce0 held at 4, waiting on crew tasks 0-2) for good (2026-11-09 run 7)
		local lag = still and not far and (e.path ~= 0 or m.walking) and m.resolved and not m.manned and not rec.placed[m.key]
			local t = lag and rec.men[m.key]
			-- a spot moved since (laid nearer its gun, or onto its man) gives him a fresh clock
			if t and (m.sx - t.sx)^2 + (m.sz - t.sz)^2 > CREW_CLOSING^2 then t = nil end
			if not lag or not t or d <= t.d - CREW_CLOSING then
				rec.men[m.key] = lag and {d = d, since = now, sx = m.sx, sz = m.sz} or nil
			elseif now - t.since >= CREW_SNAP then
				place[#place + 1] = m
				rec.men[m.key], rec.placed[m.key] = nil, true
			end
		end
	end
	for k in pairs(state.crew) do if not seen[k] then state.crew[k] = nil end end
	return place
end

-- No spot we lay goes ahead of the gun's axle (+z is the gun's front): a gun on a wall turns to face the parapet, and
-- a post ahead of it is then in the stone. CA lays posts there too; pull_crew_back (POSTS) deals with those.
local function behind(x, z) return x, math.min(z, 0) end

local function spot_try(x, z, i)
	local s, turn = SPOT_TRIES[i][1], SPOT_TRIES[i][2]
	if turn == 0 then return behind(x * s, z * s) end
	return behind(turn * z * s, -turn * x * s)
end

-- a spot's record, unless the game has laid the spot out afresh since it was written: it does that each time the
-- engine starts or stops moving (exe+308de70 calls exe+308dde4)
local function spot_record(spots, s)
	local st = spots[s.key]
	if st and math.abs(s.x - st.x) <= 0.001 and math.abs(s.z - st.z) <= 0.001 then return st end
end

-- One unit's crew spots, each {key, x, z, on_wall (its gun stands on a wall), live, off (placed off the gun's level
-- or on the ground), failed (could not be placed at all)}; returns {spot, x, z} offsets to write.
local function spot_step(spots, now, list)
	local writes, seen = {}, {}
	for _, s in ipairs(list) do
		local st, try = spot_record(spots, s), false
		seen[s.key] = true
		if not s.on_wall then
			if st then writes[#writes + 1] = {s, st.x0, st.z0} end
			st = nil
		elseif s.live and not st and (s.off or s.failed) then
			st, try = {x0 = s.x, z0 = s.z, i = 1}, true
		elseif s.live and st and s.off and not st.done and now - st.t >= SPOT_SETTLE then
			st.i, try = st.i + 1, true
			if st.i > #SPOT_TRIES then st.i, st.done = SPOT_LAST, true end
		end
		if try then
			st.x, st.z = spot_try(st.x0, st.z0, st.i)
			st.t = now
			writes[#writes + 1] = {s, st.x, st.z}
		end
		spots[s.key] = st
	end
	for k in pairs(spots) do if not seen[k] then spots[k] = nil end end
	return writes
end

-- The offset that puts a crewman's spot where he stands: the inverse of the turn the game gives an offset (sine and
-- cosine of the gun's heading, exe+1120900). Nil unless he and his gun stand on a wall, he is at its level and no
-- further from it than CA lays a spot.
local function spot_at_man(m)
	local gun = m.eng
	if not (m.on_wall and gun.on_wall) then return end
	local dx, dz = m.x - gun.bx, m.z - gun.bz
	if math.abs(m.y - gun.y) > SPOT_DROP or dx * dx + dz * dz > SPOT_REACH * SPOT_REACH then return end
	local a = math.rad(gun.turn * 360 / 65536)
	local c, s = math.cos(a), math.sin(a)
	return behind(dx * c - dz * s, dx * s + dz * c)
end

-- a spot moved onto its man is kept there, and goes back to CA's when its gun leaves the wall
local function spot_keep(spots, now, s, x, z)
	local st = spot_record(spots, s)
	spots[s.key] = {x0 = st and st.x0 or s.x, z0 = st and st.z0 or s.z, x = x, z = z, t = now, i = SPOT_LAST, done = true}
end

local function lay_spot(slot, x, z)
	mr.write(slot, SLOT.offset, x)
	mr.write(slot, SLOT.offset + 4, z)
	mr.write(slot, SLOT.angle, mr.uint16(math.floor(math.deg(math.atan2(x, z)) * 65536 / 360 + 0.5) % 65536))
	-- the game places a spot again only once its engine has moved or turned (exe+3086a80 compares the heading it
	-- placed it for, kept at +0xa8): the opposite heading there places it on the next tick
	mr.write(slot, SLOT.placed_heading, mr.uint16((mr.read_uint16(slot, SLOT.placed_heading) + 0x8000) % 65536))
end

-- every crew spot of a unit's engines, judged and written each tick of the mover
local function lay_spots(e, now)
	e.spots = e.spots or {}
	local p, list = e.ptr, {}
	local data = mr.read_pointer(p, 0x188)
	for k = 0, mr.read_int32(p, 0x184) - 1 do
		local b = mr.read_pointer(data, k * 8)
		local count, slots = mr.read_int32(b, SLOT.count), mr.read_pointer(b, SLOT.slots)
		if is_gun(b) and not mr.is_null(slots) and count > 0 and count <= SLOT_MAX then
			local on_wall, y = not mr.is_null(mr.read_pointer(b, U.surface)), mr.read_float(b, U.pos + 4)
			for j = 0, count - 1 do
				local s = mr.read_pointer(slots, j * 8)
				list[#list + 1] = {key = mr.tostring(s), ptr = s, on_wall = on_wall, live = mr.read_uint8(s, SLOT.live) == 1,
					x = mr.read_float(s, SLOT.offset), z = mr.read_float(s, SLOT.offset + 4),
					off = mr.is_null(mr.read_pointer(s, SLOT.surface)) or math.abs(mr.read_float(s, SLOT.point + 4) - y) > SPOT_DROP,
					failed = mr.read_uint8(s, SLOT.failed) == 1}
			end
		end
	end
	local writes = spot_step(e.spots, now, list)
	for _, w in ipairs(writes) do lay_spot(w[1].ptr, w[2], w[3]) end
	if #writes > 0 then log(string.format('moved %d crew spots of %s (toward their guns on a wall, or back off it)', #writes, e.unit:type())) end
end

-- An actor has moved once it leaves a circle of `radius` m (0.25 by default) around where it was last seen moving.
local function stalled(state,key,now,motion,window,radius)
	if state.motion_key~=key then
		state.motion_key,state.motion_prev,state.motion_count,state.motion_since=key,{},0,now
	end
	local next_positions,changed,r2={},#motion~=state.motion_count,(radius or 0.25)^2
	for _,p in ipairs(motion) do
		local old=state.motion_prev[p[1]]
		local moved=not old
		if old then
			local distance=(p[2]-old[2])^2+(p[3]-old[3])^2+(p[4]-old[4])^2
			local turn=p[5] and old[5] and math.abs(p[5]-old[5]) or 0
			turn=math.min(turn,65536-turn)
			moved=distance>r2 or turn>182
		end
		if moved then changed=true end
		next_positions[p[1]]=moved and {p[1],p[2],p[3],p[4],p[5]} or old
	end
	state.motion_prev,state.motion_count=next_positions,#motion
	if changed then state.motion_since=now end
	return now-state.motion_since>=(window or STALL)
end

-- An attack order on a wall battery is left alone. The game itself issues attack orders under fire at will to
-- turn a gun toward a target (the engine aims through them), so a script cannot tell the player's from the
-- engine's: turning them into the zone order re-formed the battery on every aim, eight times in 20 s for one
-- order of the player's (2026-11-03). What an attack order did to a wall battery is handled in the exe: the
-- hold, noarc, arc and inplace caves.

-- Returns a retry of the original move or nil. Body records are {x,z,on_wall}.
local function exit_step(state, s)
	if not s.move_order or #s.bodies == 0 then state.motion_key,state.engines=nil,nil return end
	local cx, cz, up = 0, 0, 0
	for _, b in ipairs(s.bodies) do
		cx, cz = cx + b[1] / #s.bodies, cz + b[2] / #s.bodies
		if b[3] and (not s.wall_order or not s.oy or math.abs((b[4] or s.oy) - s.oy) <= WALL_LEVEL) then up = up + 1 end
	end
	if up == 0 and (s.crew_wall or 0)==0 then state.motion_key,state.engines=nil,nil return end
	-- Only with every engine up: the unit's position also snaps to its ordered point once ONE engine reaches it, so
	-- three great cannon engines stood on the Altdorf wall over the fourth, down at the point, for 180 s with no
	-- recovery (2026-11-02). A split battery on its own point is a ground order that took for one engine.
	if s.ux and up == #s.bodies and (s.ox - s.ux)^2 + (s.oz - s.uz)^2 <= ATTACK_HOLD^2 then state.motion_key,state.engines=nil,nil return end
	-- An order onto a wall is done once every engine and crewman stands on it. Short of that it is recovered like
	-- any other stall, to its own point: seven crew waited at the stair foot with a wedged engine and three stood
	-- at ground level under their engine inside the gatehouse (2026-11-01), and a unit whose move never ends never
	-- fires.
	if s.wall_order and up == #s.bodies and s.crew_wall == s.crew_total then state.motion_key,state.engines=nil,nil return end
	local distance = math.sqrt((s.ox - cx)^2 + (s.oz - cz)^2)
	local motion=s.motion or {}
	if not s.motion then
		for i,b in ipairs(s.bodies)do motion[#motion+1]={i,b[1],b[4] or 0,b[2],b[5]}end
	end
	local key=string.format('ground:%.1f:%.1f:%.1f:%.1f',s.ox,s.oz,s.ob,s.ow)
	local engines={}
	for _,p in ipairs(motion) do if p[1]~='crew' then engines[#engines+1]=p end end
	state.engines=state.engines or {}
	-- Both detectors run every tick so each keeps its anchors.
	local quiet=stalled(state,key,s.now,motion,GROUND_STALL,GROUND_DRIFT)
	local wedged=stalled(state.engines,key,s.now,engines,GROUND_STALL_ENGINES,GROUND_DRIFT)
	-- Retry once when the battery stalls or one engine stays on the wrong level.
	if state.parked_key~=key then state.parked_key,state.parked,state.nudged=key,{},nil end
	local parked=false
	for i,b in ipairs(s.bodies) do
		local wrong=s.wall_order and not b[3] or not s.wall_order and b[3]
		local p=state.parked[i]
		if not wrong or not p or (b[1]-p[1])^2+(b[2]-p[2])^2>GROUND_DRIFT^2 then state.parked[i]={b[1],b[2],s.now}
		elseif s.now-p[3]>=NUDGE then parked=true end
	end
	if (parked or quiet or wedged) and not state.nudged and distance<=STALL_REACH then
		state.nudged=true
		for _,p in pairs(state.parked) do p[3]=s.now end
		state.motion_since,state.engines.motion_since=s.now,s.now
		return {'nudge',s.ox,s.oz,s.ob,s.ow,nil,nil,nil,s.wall_order or nil}
	end
end

-- An engine sent to a wall slot stops short of it against the parapet: CA lays the slots on the wall zone's marker
-- line, which is 0.5-1.2 m into the stone for an engine, and two helstorm slots 3.8 m apart leave the engines
-- touching (Altdorf, 2026-11-09). Its walk never ends (body +0x18f, "arrived", stays 0), so its go-to action never
-- ends and the engine never deploys or fires: six of eight engines stood like that. One that has stood still this
-- near its slot, on the slot's level, has its walk target and its slot moved to where it stands, and finishes the
-- walk on the next tick: its locomotion reaches its arrived state (exe+3d2b640, whose enter sets +0x18f) the
-- native way. Moving the slot too keeps the wall controller from sending it back to the old point. Nothing is
-- moved but the goal. Writing +0x18f instead fakes the arrival and leaves the locomotion in its other state
-- (exe+3d2b638): the walk ends but the engine never turns or fires again (2026-11-09 run 5, two helstorm engines).
local DOCK = {path = 0x710, walking = 4, target = 0x7f8, slot_point = 0x20, slot_body = 0x40}
local DOCK_LOG = 0.05 -- m: a settle this short moved nothing worth a log line
local DOCK_REACH = 2 -- m from its slot; a slot is at least 3.8 m from the next
local DOCK_WAIT = 1500 -- ms standing still
local DOCK_STILL = 0.1 -- m

-- The crew gate (asks 1 and 2). An engine's locomotion leaves its idle state (exe+3d2b638) only while body +0x190
-- is set, and the motion update exe+3080948 sets that each tick only when every pusher task in its list at +0xc10
-- reports its man in place. Pushers are left at the foot of a wall or on its stair, so an engine on a wall stood in
-- a walk for good, 2 m short of its slot with its locomotion idle (2026-11-09 run 6). The same update keeps the gate
-- open while the countdown at +0xdac runs, which CA sets to 10 ticks itself (exe+2f7f830). A walking engine on a
-- wall that has stood still this long with its gate shut is given that countdown: it drives on under its own
-- locomotion, and its pushers follow. Measured: 100 ticks took the run 6 engine onto its slot and it fired.
-- Off a wall the same gate held one engine of each Dark Elf reaper battery on the open ground for good (2026-11-09
-- run 21): its third pusher stood 0.3 m short of his post, beside the gun, walking and never arriving, and a repeat
-- of the order changed nothing. Given the countdown by hand once, the engine drove to its wall slot and its eight
-- crew followed. Off a wall the countdown goes only to an engine whose pushers (crew slots 0-2) all stand within
-- GATE_NEAR of it, so the crew is around (ask 1), and only after a longer wait, so CA's own pusher set-up at the start
-- of a walk is never cut short.
local GATE = {open = 0x190, grace = 0xdac}
local GATE_WAIT = 1500 -- ms standing still with the gate shut, on a wall
local GATE_WAIT_GROUND = 5000 -- ms, off a wall
local GATE_NEAR = 3 -- m from the engine to each of its pushers
local GATE_TICKS = 30 -- at 10 ticks a second

-- Records {key, ok, x, z, sx, sz, wait}: returns the ones that have been ok and stood still, on the same slot point,
-- for their own `wait` ms (or the call's), and restarts the clock of each one returned.
local function still_step(state, now, list, wait)
	local out, seen = {}, {}
	for _, d in ipairs(list) do
		seen[d.key] = true
		local st = state[d.key]
		if not d.ok then st = nil
		elseif not st or (d.x - st.x)^2 + (d.z - st.z)^2 > DOCK_STILL^2 or st.sx ~= d.sx or st.sz ~= d.sz then
			st = {x = d.x, z = d.z, sx = d.sx, sz = d.sz, since = now}
		elseif now - st.since >= (d.wait or wait) then
			out[#out + 1] = d
			st = nil
		end
		state[d.key] = st
	end
	for k in pairs(state) do if not seen[k] then state[k] = nil end end
	return out
end

-- Records are {key, walking, on_wall, x, y, z, sx, sy, sz}: an engine and the point of the slot it walks to.
-- Returns the records to settle where they stand.
local function dock_step(state, now, list)
	for _, d in ipairs(list) do
		d.ok = d.walking and d.on_wall and math.abs(d.y - d.sy) <= WALL_LEVEL and (d.x - d.sx)^2 + (d.z - d.sz)^2 <= DOCK_REACH^2
	end
	return still_step(state, now, list, DOCK_WAIT)
end

-- Records are {key, walking, on_wall, open, pushers_near, x, z}. Returns the engines to give the countdown.
local function gate_step(state, now, list)
	for _, g in ipairs(list) do
		g.ok = g.walking and not g.open and (g.on_wall or g.pushers_near)
		g.wait = g.on_wall and GATE_WAIT or GATE_WAIT_GROUND
	end
	return still_step(state, now, list)
end

-- An engine record with its crew {index, x, y, z}: true when it has a pusher and every one stands within GATE_NEAR
local function pushers_near(eng)
	local n = 0
	for _, m in ipairs(eng.crew) do
		if m.index < 3 then
			if (m.x - eng.x)^2 + (m.y - eng.y)^2 + (m.z - eng.z)^2 > GATE_NEAR^2 then return false end
			n = n + 1
		end
	end
	return n > 0
end

-- Crew posts in the parapet (ask 4). An engine fires only once deployed: vslot 0x658 (exe+307145c) is
-- (+0xce0 & 0x1080000) == 0x80000, and each deploy step waits on crew tasks in the list at +0xc10. A task walks its man
-- to its own target, offset +0x38/+0x3c from the gun (+z is the gun's front) and world point +0x48/+0x50, copied from
-- the engine's spot table at +0xcc0 (0x50-byte rows keyed by task type, offsets at +0x30/+0x38/+0x40), which mirrors
-- the crew slots as the game last laid them. CA lays pushers ahead of the gun too ((1.5,1.5) and (3,1.5) in the pusher
-- rows, types 23 and 24), so an engine that stops facing a parapet can copy a post 1-1.5 m ahead: inside the stone.
-- Its man walks at the stone for good, the deploy holds at +0xce0 = 4, and the engine never fires, whatever it is
-- ordered to shoot (2026-11-09 runs 6-9: two to four of four docked helstorms, 0 shots against 4-5 beside them).
-- On a wall, a standing engine's crew posts ahead of it are pulled back level with the gun; with that done by hand,
-- all four fired (run 8). The pusher layout rows are not touched: they are where the men push from when it moves.
local POSTS = {rows = 0xcc0, row_count = 0xcbc, row_size = 0x50, row_type = 0x20, row_z = {0x34, 0x3c, 0x44},
	tasks = 0xc10, task_count = 0xc0c, task_x = 0x38, task_z = 0x3c, task_at = 0x48, crew_types = 18,
	slack = 0.01} -- m: a float32 write reads back a hair off, and must not count as pulling again

-- Turning on a wall (ask 4). Deploy step 0x1d faces the gun at its target (exe+3066250, as exe+30753e4): a target
-- outside the gun's traverse turns the engine in place through exe+308cfa0, at the point kept in its anchor at +0xd10.
-- CA sets the anchor from the engine's placement block at +0xd78 (exe+306d7d8 copies 0x20 bytes: location, heading,
-- surface) and the wall controller's moves never do, so on a wall the anchor is still the engine's start-of-battle spot
-- on the ground. The turn became a walk there, re-sent each tick: the locomotion left its arrived state every tick,
-- +0xcfc held "moving", and the deploy never started (2026-11-09 run 11: four docked helstorms, 0 shots, goal +0x1e0
-- 255 m off at the battle start). A standing engine on a wall, or one whose anchor is still up on a wall, gets its
-- placement copied into the anchor, as CA's own setter does.
local ANCHOR = {at = 0xd10, laid = 0xd78, size = 0x20, reach = 1}

-- returns true when it moved the anchor
local function anchor_step(b, on_wall)
	local ax, ay, az = mr.read_float(b, ANCHOR.at), mr.read_float(b, ANCHOR.at + 4), mr.read_float(b, ANCHOR.at + 8)
	local px, py, pz = mr.read_float(b, ANCHOR.laid), mr.read_float(b, ANCHOR.laid + 4), mr.read_float(b, ANCHOR.laid + 8)
	if (ax - px)^2 + (az - pz)^2 <= ANCHOR.reach^2 then return false end
	if not on_wall and math.abs(ay - py) <= WALL_LEVEL then return false end
	for o = 0, ANCHOR.size - 2, 2 do mr.write(b, ANCHOR.at + o, mr.uint16(mr.read_uint16(b, ANCHOR.laid + o))) end
	return true
end

-- The turn is bounded too: exe+308cfa0 clamps the heading it asks for to +-25 degrees (half the 0.8727 rad at
-- +0x2d8 -> +0x70) around +0xd9a, the heading the unit last placed the engine at (exe+307f434 / 307fb30, which write
-- it with the anchor). The wall controller never writes it either, so on a wall it is still the engine's heading on
-- the ground at the start of the battle: run 12's helstorms (145 there) could only turn between 120 and 170 on a wall
-- facing 180, stopped at 170, and never fired at a target at 226. Set to the slot's heading by hand, they turned to
-- 205 and three of four fired 14-16 times in 661 s; the fourth's target, at 227, was past 205 plus its own traverse.
-- An engine standing on a wall gets its slot's heading there.
local BASE = 0xd9a

-- heading: the slot's, in 1/65536 of a turn. Returns true when it wrote
local function base_step(b, heading)
	local h = math.floor(heading + 0.5) % 65536
	if mr.read_uint16(b, BASE) == h then return false end
	mr.write(b, BASE, mr.uint16(h))
	return true
end

-- A gun shoved off its deploy. A deployed engine on a wall that another battery walks past is pushed a few tenths of
-- a metre and packs: +0xce0, +0xce4 and +0xcec all 0. Its fire command (vtable exe+3adf528, embedded at +0x330)
-- hands the target over once (exe+3077880, guarded by the command's +0xc4), and the unit's target has not changed,
-- so nothing asks for the deploy again and the gun stands packed for good, a re-click on the same target included
-- (2026-11-09 run 10, and run 13: the two cannons east of the stairs the helstorms walked past, 3 shots each against
-- 12-13 beside them). Cleared +0xc4 by hand, both redeployed and fired within 4 s. One that has stood packed for
-- REDEPLOY_WAIT with a target gets its command's +0xc4 cleared, so the command hands the target over again.
local REDEPLOY = {cmd = 0x330, handed = 0xc4, aim = 0xc8c, flags = {0xce0, 0xce4, 0xcec}}
local REDEPLOY_WAIT = 3000 -- ms standing packed

-- the engine holds a handed-over command with a target and is packed with nothing in progress or pending
local function stands_packed(b)
	if mr.read_uint8(mr.add(b, REDEPLOY.cmd), REDEPLOY.handed) ~= 1 or mr.read_uint8(b, REDEPLOY.aim) ~= 1 then return false end
	for _, o in ipairs(REDEPLOY.flags) do if mr.read_int32(b, o) ~= 0 then return false end end
	return true
end

-- "Level with the gun" is level along the wall, not along the gun. The parapet runs along the slot heading (+0xd9a,
-- base_step), and a gun turned off it swings one side's posts forward: a post 1.8 m to the side of a cannon turned 23
-- degrees stands 0.7 m further out, in the stone (2026-11-09 run 16: two of four docked cannons, 0 shots in 5 min, each
-- with a man walking at a post 0.3-0.5 m past the parapet face). A post (x to the gun's side, z ahead of it) reaches
-- e = x sin(t) + z cos(t) toward the face, t = wall - gun; one with e > 0 is moved straight back off the face by e, and
-- no post is left ahead of the gun. That holds at any angle: a bolt thrower laid 65 degrees off its slot kept two posts
-- in the stone under the old rule (z <= -x tan(t), t clamped at 30), its deploy waited on them for good and it fired 2
-- shots to the other seven's 42-49 (2026-11-09 run 30). And it moves a post at most its own distance from the gun, so
-- a stale +0xd9a cannot send a man far.

-- returns how many posts it pulled back
local function pull_crew_back(b)
	local t = math.rad((mr.read_uint16(b, BASE) - mr.read_uint16(b, SPOT_GUN.turn)) * 360 / 65536)
	local sn, cs = math.sin(t), math.cos(t)
	local function level(x, z)
		local e = x * sn + z * cs
		if e > POSTS.slack then x, z = x - e * sn, z - e * cs end
		return x, math.min(z, 0)
	end
	local function moved(x0, z0, x, z) return z0 > z + POSTS.slack or math.abs(x - x0) > POSTS.slack end
	local n, rows = 0, mr.read_pointer(b, POSTS.rows)
	for j = 0, mr.read_int32(b, POSTS.row_count) - 1 do
		local r = mr.add(rows, j * POSTS.row_size)
		if mr.read_int32(mr.read_pointer(r, POSTS.row_type), 0) <= POSTS.crew_types then
			local pulled = false
			for _, o in ipairs(POSTS.row_z) do -- each copy's x is the float before its z
				local x0, z0 = mr.read_float(r, o - 4), mr.read_float(r, o)
				local x, z = level(x0, z0)
				if moved(x0, z0, x, z) then mr.write(r, o - 4, x) mr.write(r, o, z) pulled = true end
			end
			if pulled then n = n + 1 end
		end
	end
	local a = math.rad(mr.read_uint16(b, SPOT_GUN.turn) * 360 / 65536)
	local c, s = math.cos(a), math.sin(a)
	local list = mr.read_pointer(b, POSTS.tasks)
	for j = 0, mr.read_int32(b, POSTS.task_count) - 1 do
		local tk = mr.read_pointer(list, j * 8)
		local x0, z0 = mr.read_float(tk, POSTS.task_x), mr.read_float(tk, POSTS.task_z)
		local x, z = level(x0, z0)
		if moved(x0, z0, x, z) then
			mr.write(tk, POSTS.task_x, x)
			mr.write(tk, POSTS.task_z, z)
			mr.write(tk, POSTS.task_at, mr.read_float(b, SPOT_GUN.base) + x * c + z * s)
			mr.write(tk, POSTS.task_at + 8, mr.read_float(b, SPOT_GUN.base + 8) - x * s + z * c)
			n = n + 1
		end
	end
	return n
end

-- Retry CA's wall order once, retaining its zone and surface. A battery is done once every engine has finished its
-- walk on its slot. Its crew are not asked for: the pushers stay at the wall foot, so a docked and firing helstorm
-- battery read as stalled and was re-ordered and scrambled (2026-11-09 run 6, 381 s); the crew gate is for them.
-- A turn or a shuffle on the spot is not progress: at the stair head by x 685 a whole battery stood with every
-- slot dropped by the wall controller, two engines turning through every heading and wandering within a metre for
-- good, so the retry never came (2026-11-09 runs 19 and 22, flame cannons and reapers; the same order by hand
-- docked them). The engines go into s.motion without their heading, and the stall test allows WALL_DRIFT.
local WALL_DRIFT = 2 -- m: an engine walking along the wall covers this in 2 s
local function wall_step(state,s)
	if #s.slots ~= s.engine_count or #s.slots == 0 then return end
	if s.engines_arrived==s.engine_count then state.motion_key=nil return end
	if state.wall_recovered==s.key then return end
	if not stalled(state,'wall:'..s.key,s.now,s.motion,nil,WALL_DRIFT) or s.distance>STALL_REACH then return end
	state.wall_recovered = s.key
	return {'wall',s.request}
end

-- BCQ_MULTIPLE_SELECTION_ORDER_DEFEND_BATTLEFIELD_ZONE, the same constructor and
-- typed queue writer used by a wall right-click (2e5541b/2e5542f on this build).
local function queue_wall(e,t)
	local battle = mr.read_pointer(at({0x448,0xf208}),0)
	local context = mr.read_pointer(battle,0x468)
	assert(mr.read_uint8(context,0x3b0)==0 and mr.read_uint8(context,0x3b1)==0,'battle queue is gated')
	local queue = mr.read_pointer(context,0x644e8)
	local selection,command,point = mr.alloc(0x80),mr.alloc(0xb0),mr.alloc(8)
	mr.write(point,0,t.x); mr.write(point,4,t.z)
	mr.call(at({0x2f3,0x6408}),'pointer(pointer)',selection)
	mr.call(at({0x2f3,0xf044}),'pointer(pointer,pointer,uint8)',selection,e.ptr,0)
	mr.call(at({0x2eb,0x09c8}),'pointer(pointer,pointer,pointer,pointer,pointer,uint8,uint8)',
		command,selection,t.zone,point,t.surface,0,0)
	local result = mr.call(at({0x2df,0xcac4}),'uint8(pointer,pointer)',queue,command)
	mr.call(at({0x1bd,0x3f4c}),'pointer(pointer)',mr.add(command,8))
	mr.call(at({0x1bd,0x3f4c}),'pointer(pointer)',selection)
	assert(mr.tostring(result)=='1','native wall order was not queued')
end

local ORDER_LOCATION = 0x40

-- The player's own MOVE for the unit to a location block on a wall, with a facing and a width. A script goto onto a
-- wall point is silently dropped: goto_location_angle_width (exe+2ed8b7c) resolves its point to the ground first.
-- This builds the same command it builds next (exe+2ea9c88: the location, a u16 heading at +0xa8, the width at
-- +0xac, run at +0xb0) from a location block that keeps the wall surface, and queues it the same way (exe+2e9c154).
-- Given the order's own block it is a re-click of the player's point. The facing is the point of it: the builder
-- without one (exe+2ea9a94) took its bearing from the walk, and every re-click and recovery walk left the battery
-- facing along the wall, where it never fires (2026-11-02, three runs).
local function queue_move(e,block,facing,width)
	local battle = mr.read_pointer(at({0x448,0xf208}),0)
	local context = mr.read_pointer(battle,0x468)
	assert(mr.read_uint8(context,0x3b0)==0 and mr.read_uint8(context,0x3b1)==0,'battle queue is gated')
	local queue = mr.read_pointer(context,0x644e8)
	local selection,command,location = mr.alloc(0x80),mr.alloc(0xc0),mr.alloc(0x20)
	for off=0,8,4 do mr.write(location,off,mr.read_float(block,off)) end
	mr.write(location,0xc,mr.uint32(0))
	assert(not mr.is_null(mr.read_pointer(block,0x10)),'the order carries no wall surface')
	mr.write(location,0x10,mr.read_pointer(block,0x10))
	mr.write(location,0x18,mr.read_pointer(block,0x18))
	mr.call(at({0x2f3,0x6408}),'pointer(pointer)',selection)
	mr.call(at({0x2f3,0xf044}),'pointer(pointer,pointer,uint8)',selection,e.ptr,0)
	-- heading and width go in after the build: the call bridge passes integers, and the width is a float
	mr.call(at({0x2eb,0x0efc}),'pointer(pointer,pointer,pointer,uint32,uint32,uint8,uint8)',command,selection,location,0,0,0,0)
	mr.write(command,0xa8,mr.uint16(math.floor(facing*65536/360+0.5)%65536))
	mr.write(command,0xac,width)
	local result = mr.call(at({0x2ea,0x33c8}),'uint8(pointer,pointer)',queue,command)
	mr.call(at({0x1bd,0x3f4c}),'pointer(pointer)',mr.add(command,8))
	mr.call(at({0x1bd,0x3f4c}),'pointer(pointer)',selection)
	assert(mr.tostring(result)=='1','wall move was not queued')
end

local function start_mover(entries)
	local move_vt,wall_vt,fire_vt = mr.tostring(at({0x391,0x9980})),mr.tostring(at({0x391,0xd440})),mr.tostring(at({0x3ad,0xf528}))
	local act
	local function finish(e,ok,err)
		e.controller:release_control()
		e.pending,e.motion_key,e.cool = false,nil,bm:time_elapsed_ms()+COOL
		if not ok then log('order retry failed: '..tostring(err)) end
	end
	local function update(e)
		local now, p = bm:time_elapsed_ms(), e.ptr
		if e.pending or now < (e.cool or 0) then return end
		local controllers = mr.read_int32(p,0x3310)
		local c = controllers==1 and mr.read_pointer(p,0x3300) or nil
		local on_wall = c and mr.tostring(mr.read_pointer(c,0))==wall_vt
		local orders = mr.read_int32(p,0x2f88)
		local order = mr.add(p,0x2a0 + mr.read_int32(p,0x2f8c) * 0x120)
		local order_vt = orders > 0 and mr.tostring(mr.read_pointer(order,0))
		local active = controllers == 0 and order_vt == move_vt
		if not on_wall then e.wall_recovered = nil end
		local u,bodies,engines = e.unit,{},{}
		if not active and not on_wall then e.motion_key=nil return end
		local data = mr.read_pointer(p,0x188)
		for k=0,mr.read_int32(p,0x184)-1 do
			local b = mr.read_pointer(data,k*8)
			bodies[#bodies+1] = {mr.read_float(b,U.pos),mr.read_float(b,U.pos+8),
				not mr.is_null(mr.read_pointer(b,U.surface)),mr.read_float(b,U.pos+4),mr.read_uint16(b,U.heading),mr.tostring(b),
				mr.read_int32(b,DOCK.path)}
			local eng,slots = {key=mr.tostring(b),ptr=b,x=mr.read_float(b,U.pos),y=mr.read_float(b,U.pos+4),z=mr.read_float(b,U.pos+8),crew={},
				bx=mr.read_float(b,SPOT_GUN.base),bz=mr.read_float(b,SPOT_GUN.base+8),turn=mr.read_uint16(b,SPOT_GUN.turn),
				on_wall=not mr.is_null(mr.read_pointer(b,U.surface)),open=mr.read_uint8(b,GATE.open)==1,
				cmd=mr.tostring(mr.read_pointer(b,0x330)),done=mr.read_uint8(b,0x340),path=mr.read_int32(b,0x710)},mr.read_pointer(b,SLOT.slots)
			-- One engine's slot table can be unreadable (an engine down off the wall with the rest still up read as
			-- 'failed to read memory' twice a tick for 1,000 s, 2026-11-01 22:40, and no ground recovery ever ran).
			-- That engine goes in with no crew; the bodies list and the recovery must not depend on it.
			if is_gun(b) then
			local count = mr.read_int32(b,SLOT.count)
			local readable, why = pcall(function()
				if mr.is_null(slots) or count < 0 or count > SLOT_MAX then error('slot table '..mr.tostring(slots)..' count '..count) end
				for j=0,count-1 do
					local s = mr.read_pointer(slots,j*8)
					local m = mr.read_pointer(s,SLOT.man)
					if not mr.is_null(m) then
						eng.crew[#eng.crew+1] = {key=mr.tostring(m),ptr=m,index=j,x=mr.read_float(m,U.pos),y=mr.read_float(m,U.pos+4),z=mr.read_float(m,U.pos+8),
							sx=mr.read_float(s,SLOT.point),sy=mr.read_float(s,SLOT.point+4),sz=mr.read_float(s,SLOT.point+8),
							resolved=mr.read_uint8(s,SLOT.resolved)==1,manned=mr.read_uint8(s,SLOT.manned)==1,eng=eng,
							walking=mr.read_int32(m,DOCK.path)==DOCK.walking,
							slot=s,spot={key=mr.tostring(s),x=mr.read_float(s,SLOT.offset),z=mr.read_float(s,SLOT.offset+4)},
							on_wall=not mr.is_null(mr.read_pointer(m,U.surface))}
					end
				end
			end)
			if not readable then
				eng.crew = {}
				e.unreadable = e.unreadable or {}
				if not e.unreadable[eng.key] then
					e.unreadable[eng.key] = true
					log(string.format('engine %s of %s: crew slots unreadable (%s); recovering without its crew',eng.key,u:type(),tostring(why)))
				end
			end
			engines[#engines+1] = eng
			end
		end
		e.gates,e.gated = e.gates or {},e.gated or {}
		local gates = {}
		for _,eng in ipairs(engines) do
			gates[#gates+1] = {key=eng.key,ptr=eng.ptr,walking=eng.path==DOCK.walking,on_wall=eng.on_wall,open=eng.open,x=eng.x,z=eng.z,
				pushers_near=pushers_near(eng)}
		end
		for _,g in ipairs(gate_step(e.gates,now,gates)) do
			mr.write(g.ptr,GATE.grace,mr.uint32(GATE_TICKS))
			local seen = g.key..(g.on_wall and ':wall' or ':ground')
			if not e.gated[seen] then
				e.gated[seen] = true
				log(g.on_wall and string.format('an engine of %s on a wall waited for its crew: moving it on without them',u:type())
					or string.format('an engine of %s waited for a pusher standing beside it: moving it on',u:type()))
			end
		end
		e.pulled, e.anchored = e.pulled or {}, e.anchored or {}
		for _,eng in ipairs(engines) do
			if eng.on_wall and eng.path ~= DOCK.walking and pull_crew_back(eng.ptr) > 0 and not e.pulled[eng.key] then
				e.pulled[eng.key] = true
				log(string.format('an engine of %s on a wall had crew posts in the parapet: moved them back level with the gun',u:type()))
			end
			if eng.path ~= DOCK.walking and anchor_step(eng.ptr, eng.on_wall) and not e.anchored[eng.key] then
				e.anchored[eng.key] = true
				log(string.format('an engine of %s turned toward a point it had left (on the ground or up a wall): moved that point to where it stands',u:type()))
			end
		end
		local packed = {}
		for _,eng in ipairs(engines) do
			packed[#packed+1] = {key=eng.key,ptr=eng.ptr,x=eng.x,z=eng.z,sx=0,sz=0,
				ok=eng.on_wall and eng.path ~= DOCK.walking and eng.cmd == fire_vt and stands_packed(eng.ptr)}
		end
		e.packed, e.redeployed = e.packed or {}, e.redeployed or {}
		for _,g in ipairs(still_step(e.packed,now,packed,REDEPLOY_WAIT)) do
			mr.write(mr.add(g.ptr,REDEPLOY.cmd),REDEPLOY.handed,mr.uint8(0))
			if not e.redeployed[g.key] then
				e.redeployed[g.key] = true
				log(string.format('an engine of %s on a wall stood packed with a target: asked for its deploy again',u:type()))
			end
		end
		for _,m in ipairs(crew_step(e,now,engines)) do
			local x,z = spot_at_man(m)
			if x then
				e.spots = e.spots or {}
				lay_spot(m.slot,x,z)
				spot_keep(e.spots,now,m.spot,x,z)
				log(string.format('moved a crew spot onto its man (%s) %.1f m; engine path %d',u:type(),math.sqrt((m.x-m.sx)^2+(m.z-m.sz)^2),m.eng.path))

			end
		end
		local total,crew,men = mr.read_int32(p,0xa4),0,mr.read_pointer(p,0xa8)
		local motion={}
		for k=0,total-1 do
			local m=mr.read_pointer(men,k*8)
			local above=not mr.is_null(mr.read_pointer(m,U.surface))
			if above then crew=crew+1 end
			if on_wall and not above then
				motion[#motion+1]={'m'..mr.tostring(m),mr.read_float(m,U.pos),mr.read_float(m,U.pos+4),mr.read_float(m,U.pos+8)}
			end
		end
		local action
		if on_wall then
			local n = mr.read_int32(c,0x154)
			if n==0 or n~=#bodies then return end
			local slots,targets,d,docks = {},{},mr.read_pointer(c,0x158),{}
			local first = mr.read_pointer(d,0)
			local zone = mr.read_pointer(c,0x98)
			for k=0,n-1 do
				local s=mr.read_pointer(d,k*8)
				local b=mr.read_pointer(s,DOCK.slot_body)
				if not mr.is_null(b) and is_gun(b) then
					docks[#docks+1]={key=mr.tostring(s),slot=s,body=b,walking=mr.read_int32(b,DOCK.path)==DOCK.walking,
						on_wall=not mr.is_null(mr.read_pointer(b,U.surface)),x=mr.read_float(b,U.pos),y=mr.read_float(b,U.pos+4),
						z=mr.read_float(b,U.pos+8),sx=mr.read_float(s,DOCK.slot_point),sy=mr.read_float(s,DOCK.slot_point+4),
						sz=mr.read_float(s,DOCK.slot_point+8)}
				end
			end
			e.docks=e.docks or {}
			for _,dk in ipairs(dock_step(e.docks,now,docks)) do
				mr.write(dk.body,DOCK.target,dk.x); mr.write(dk.body,DOCK.target+8,dk.z)
				mr.write(dk.slot,DOCK.slot_point,dk.x); mr.write(dk.slot,DOCK.slot_point+8,dk.z)
				local short=math.sqrt((dk.x-dk.sx)^2+(dk.z-dk.sz)^2)
				if short>=DOCK_LOG then log(string.format('settled an engine of %s %.1f m short of its wall slot',u:type(),short)) end
			end
			for k=0,n-1 do
				local s=mr.read_pointer(d,k*8)
				slots[#slots+1]={mr.read_float(s,0x20),mr.read_float(s,0x28)}
				local row=mr.read_pointer(s,0x18)
				local heading=bearing_to(0,0,mr.read_float(row,0x28),mr.read_float(row,0x2c))*65536/360
				targets[mr.tostring(mr.read_pointer(s,0x40))]={slots[#slots][1],mr.read_float(s,0x24),slots[#slots][2],heading}
			end
			e.based = e.based or {}
			for _,eng in ipairs(engines) do
				local t = targets[eng.key]
				if t and eng.on_wall and eng.path ~= DOCK.walking and base_step(eng.ptr, t[4]) and not e.based[eng.key] then
					e.based[eng.key] = true
					log(string.format('an engine of %s on a wall turned around its heading on the ground: centred that on its slot',u:type()))
				end
			end
			local arrived,distance=0,0
			for _,b in ipairs(bodies)do
				local t=targets[b[6]]
				local range=(b[1]-(t and t[1] or slots[1][1]))^2+(b[2]-(t and t[3] or slots[1][2]))^2+
					(b[4]-(t and t[2] or mr.read_float(first,0x24)))^2
				distance=math.max(distance,math.sqrt(range))
				-- arrived: on its slot with its walk over; a heading test read an engine turned to aim as stalled
				if t and b[3] and range<=1 and b[7]~=DOCK.walking then arrived=arrived+1
				else motion[#motion+1]={'b'..b[6],b[1],b[4],b[2]} end -- no heading: see WALL_DRIFT
			end
			for _,actor in ipairs(motion)do
				if actor[1]:sub(1,1)=='m' then
					distance=math.max(distance,math.sqrt((actor[2]-slots[1][1])^2+
						(actor[3]-mr.read_float(first,0x24))^2+(actor[4]-slots[1][2])^2))
				end
			end
			-- the first slot's marker row, not its point: the point is moved when an engine is settled short of it
			local key=mr.tostring(zone)..':'..mr.tostring(mr.read_pointer(first,0x18))
			action=wall_step(e,{key=key,now=now,distance=distance,motion=motion,engine_count=#bodies,engines_arrived=arrived,crew_wall=crew,crew_total=total,
				slots=slots,
				request={zone=zone,x=slots[1][1],z=slots[1][2],surface=mr.read_pointer(first,0x30)}})
		else
			-- No heading: an engine turning in place at a wall edge is not on its way down.
			for _,b in ipairs(bodies)do motion[#motion+1]={'b'..b[6],b[1],b[4],b[2]} end
			-- Crew left on a wall shuffle in place for ever (four of 54 moved over a metre in one second while every
			-- engine stood still, 2026-11-01), which blocked every ground recovery. A crewman getting down is the
			-- progress that counts, so the count stands in for the crew: each one is a hundred metres, past any drift.
			motion[#motion+1]={'crew',crew*100,0,0}
			local dest, pos = u:ordered_position(), u:position()
			-- A move onto a walkway point outside a wall zone is a plain MOVE at wall height; the engines climb it
			-- on their own and a stall is recovered to that point, never to the ground.
			local wall_order = dest:get_y()-bm:get_terrain_height(dest:get_x(),dest:get_z())>WALL_TOP
			action = exit_step(e,{now=now,move_order=true,bodies=bodies,motion=motion,crew_wall=crew,crew_total=total,wall_order=wall_order,
				ox=dest:get_x(),oy=dest:get_y(),oz=dest:get_z(),ob=u:ordered_bearing(),ow=u:ordered_width(),ux=pos:get_x(),uz=pos:get_z()})
		end
		if not action then return end
		act(e,action,order)
	end
	act = function(e,action,order)
		local u = e.unit
		log('recovering stalled '..u:type()..' ('..action[1]..')')
		e.pending = true
		e.controller:take_control()
		local fine,why = pcall(function()
			if action[1]=='wall' then
				queue_wall(e,action[2])
			elseif action[9] then
				queue_move(e,mr.add(order,ORDER_LOCATION),action[4],action[5])
			else
				e.controller:goto_location_angle_width(battle_vector:new(action[2],0,action[3]),action[4],action[5])
			end
		end)
		finish(e,fine,why)
	end
	bm:repeat_callback(function()
		if bm.current_phase == 'Deployment' then return end
		for _,e in ipairs(entries) do
			local ok, err = pcall(update,e)
			if not ok then log('movement recovery read failed: '..tostring(err)) end
			ok, err = pcall(lay_spots,e,bm:time_elapsed_ms())
			if not ok and not e.spot_failed then e.spot_failed = true log('crew spot read failed: '..tostring(err)) end
		end
	end,500,'derpy_artillery_walls_exit')
end

